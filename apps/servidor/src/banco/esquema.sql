# Banco de dados

## Responsável: Dev 1

## O que esse arquivo deve conter

- Schema com usuários.
- Tabela de personagens.
- Tabela de salas e partidas.
- Estruturas para inventário e status.

## Conexão com o projeto

A persistência do jogo depende deste arquivo para salvar jogadores, personagens e estado da partida.

## Planejamento por semanas

### Semana 1
- Modelar usuários e personagens.

### Semana 2
- Adicionar salas e partidas.

### Semana 3+
- Expandir para itens, inventário e status avançados.
